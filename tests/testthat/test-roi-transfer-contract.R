test_that("metadata frames validate calibration and nonbinary pyramid transforms", {
  f <- sg_roi_frame(c(100, 80), list(c(100, 80), c(30, 20)), c(0.5, 0.8), "um")
  r <- sg_roi_rect(0, 0, 30, 20, "tissue", level = 1L)
  r0 <- sg_roi_transform(r, 1L, 0L, f)
  expect_equal(sg_roi_bbox(r0), c(0, 0, 100, 80))
  expect_equal(sg_roi_bbox(sg_roi_transform(r0, 0L, 1L, f)), c(0, 0, 30, 20))
  expect_error(sg_roi_frame(c(1.5, 2)), "Dimensions")
  expect_error(sg_roi_frame(c(2, 2), pixel_size = c(0, 1)), "pixel_size")
  expect_error(sg_roi_frame(c(2, 2), list(c(2, 2), c(3, 1))), "must not increase")
})
test_that("mask calibration preserves anisotropic single-pixel area and missingness", {
  r <- sg_roi_rect(1, 2, 2, 3, "cell")
  m <- sg_roi_mask(r, dims = c(4, 4), type = "labelled")
  expect_equal(which(as.matrix(m) > 0, arr.ind = TRUE), matrix(c(3L, 2L), 1L, dimnames = list(NULL, c("row", "col"))))
  expect_equal(sg_roi_mask_stats(m, c(0.5, 0.8))$area_physical, 0.4)
  expect_true(is.na(sg_roi_mask_stats(m)$area_physical))
  expect_error(sg_roi_mask_stats(m, c(-1, 1)), "pixel_size")
})
test_that("QuPath direct roundtrip retains noninteger holes, identity and metadata", {
  outer <- rbind(c(0.25,0.5),c(9.75,0.5),c(9.75,8.5),c(0.25,8.5),c(0.25,0.5))
  hole <- rbind(c(2.25,2.5),c(2.25,4.5),c(4.25,4.5),c(4.25,2.5),c(2.25,2.5))
  r <- sg_roi_polygon(list(outer,hole), "cell", id = "stable-cell")
  r$attributes$qupath <- list(object_type="cell", metadata=list(review="pending"),
    nucleus_geometry=list(type="Point",coordinates=list(3,3)),
    measurements=tibble::tibble(name=c("Area", "Signal"),value=c(72,NaN),value_state=c("finite","nan")))
  r$attributes$plane <- list(c=1L,z=2L,t=3L)
  p <- sg_roi_project(sg_roi_frame(c(20,20)),sg_roi_layer_add(sg_roi_layer("cells"),r))
  path <- tempfile(fileext=".geojson");on.exit(unlink(path))
  sg_roi_write_qupath(p,path)
  back <- sg_roi_read_qupath(path)$rois[[1L]]
  expect_identical(sf::st_as_binary(back$geometry),sf::st_as_binary(r$geometry))
  expect_identical(back$id,r$id)
  expect_identical(back$attributes$plane,r$attributes$plane)
  expect_identical(back$attributes$qupath$metadata$review,"pending")
  expect_identical(back$attributes$qupath$measurements$value_state,c("finite","nan"))
  expect_equal(back$attributes$qupath$nucleus_geometry,r$attributes$qupath$nucleus_geometry)
  expect_error(sg_roi_write_qupath(p,path),"already exists")
  raw_hash <- digest::digest(charToRaw("annotatR:roi:stable-cell"),algo="sha256",serialize=FALSE)
  expect_identical(substr(.sg_roi_roi_uuid("stable-cell"),1,8),substr(raw_hash,1,8))
})
